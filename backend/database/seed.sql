catalog AS (
    SELECT role.slug, title, cluster, summary, tags, niche_pivot_friendly,
           career_field, specializations, education_requirements,
           ARRAY(SELECT tag FROM unnest(tags) AS t(tag)
                 WHERE tag NOT IN ('analytics', 'creativity', 'people', 'structure', 'autonomy')) AS interests,
           demand, ai_impact, key_skills,
           jsonb_build_object(
               'market', 'US', 'currency', 'USD', 'period', 'year', 'basis', 'base_pay',
               'entry', jsonb_build_object('min', entry_pay[1], 'max', entry_pay[2]),
               'mid', jsonb_build_object('min', mid_pay[1], 'max', mid_pay[2]),
               'senior', jsonb_build_object('min', senior_pay[1], 'max', senior_pay[2])
           ) AS salary_tiers
    FROM legacy_roles AS role
    JOIN legacy_paths USING (slug)
    UNION ALL
    SELECT slug, title, cluster, summary, traits || interests, false,
           career_field, specializations, education_requirements, interests,
           demand, ai_impact, key_skills, NULL::jsonb
    FROM new_roles
)
INSERT INTO career_roles (slug, title, cluster, summary, tags, niche_pivot_friendly, market_pulse)
SELECT slug, title, cluster, summary, tags, niche_pivot_friendly,
       jsonb_build_object(
           'career_field', career_field,
           'specializations', to_jsonb(specializations),
           'education_requirements', education_requirements,
           'education_market', 'US',
           'interests', to_jsonb(interests),
           'demand', demand,
           'ai_impact', ai_impact,
           'market_data_basis', 'qualitative_seed_estimate',
           'salary_tiers', salary_tiers,
           'salary_data_basis', CASE WHEN salary_tiers IS NULL THEN 'unavailable' ELSE 'illustrative' END,
           'key_skills', to_jsonb(key_skills)
       )
FROM catalog
-- Add missing metadata to previously seeded roles while preserving IDs and catalog edits.
ON CONFLICT (slug) DO UPDATE
SET market_pulse = EXCLUDED.market_pulse || career_roles.market_pulse
WHERE career_roles.market_pulse IS DISTINCT FROM (EXCLUDED.market_pulse || career_roles.market_pulse);

COMMIT;
